/** Deterministic Markdown renderer. Coverage is printed, never implied. */

import { coverageSummary } from "../coverage.mjs";

function yamlValue(value) {
  return String(value ?? "unknown").replace(/[\r\n]+/g, " ").replace(/"/g, '\\"');
}

function fence(content) {
  const text = String(content ?? "");
  const longest = Math.max(3, ...(text.match(/`+/g) ?? []).map((run) => run.length + 1));
  const marker = "`".repeat(longest);
  return `${marker}text\n${text}\n${marker}`;
}

export function renderMarkdown(view, options = {}) {
  const generatedAt =
    options.generatedAt ?? view.conversation?.captured_at ?? view.conversation?.updated_at ?? "unknown";
  const coverage = view.coverage ?? {};
  const lines = [];
  lines.push("---");
  lines.push("schema_version: 2");
  lines.push("export_format: markdown");
  lines.push(`conversation_id: "${yamlValue(view.conversation?.id)}"`);
  lines.push(`title: "${yamlValue(view.conversation?.title)}"`);
  lines.push(`source_adapter: "${yamlValue(view.source?.adapter)}"`);
  lines.push(`source_kind: "${yamlValue(view.source?.kind)}"`);
  lines.push(`source_boundary: "${yamlValue(view.boundary?.kind)}"`);
  lines.push(`coverage_source: ${coverage.source?.status ?? "UNKNOWN"}`);
  lines.push(`coverage_selection: ${coverage.selection?.status ?? "UNKNOWN"}`);
  lines.push(`coverage_export: ${coverage.export?.status ?? "UNKNOWN"}`);
  lines.push(`record_count: ${view.records.length}`);
  lines.push(`generated_at: "${yamlValue(generatedAt)}"`);
  if (options.rawSha256) lines.push(`raw_sha256: ${options.rawSha256}`);
  if (options.viewSha256) lines.push(`view_sha256: ${options.viewSha256}`);
  lines.push("---");
  lines.push("");
  lines.push(`# ${view.conversation?.title ?? "Conversation"}`);
  lines.push("");
  lines.push("## Coverage");
  lines.push("");
  lines.push("| Dimension | Status | Evidence |");
  lines.push("| --- | --- | --- |");
  for (const dimension of ["source", "selection", "export"]) {
    const entry = coverage[dimension] ?? {};
    lines.push(
      `| ${dimension} | ${entry.status ?? "UNKNOWN"} | ${String(entry.reason ?? "").replace(/\|/g, "\\|")} |`,
    );
  }
  lines.push("");
  const boundaryLabel = `Boundary: \`${view.boundary?.kind ?? "unknown"}\` · ${coverageSummary(coverage)}`;
  lines.push(boundaryLabel);
  if (view.boundary?.history_complete === false) {
    lines.push("");
    lines.push("> This export is complete only relative to the stated boundary; it is not a complete history.");
  }
  lines.push("");
  lines.push("## Messages");
  lines.push("");
  if (view.records.length === 0) {
    lines.push("_No records were captured._");
    lines.push("");
  }
  view.records.forEach((record, index) => {
    const time = record.timestamp ?? "unknown time";
    lines.push(`### ${index + 1}. ${String(record.role).toUpperCase()} · ${time}`);
    lines.push("");
    lines.push(
      `<!-- export:record id=${record.id} seq=${record.seq} provenance=${record.provenance} hash=${record.hash} -->`,
    );
    lines.push("");
    if (record.unknown || record.type === "unknown") {
      lines.push("> UNKNOWN record. Raw source evidence is preserved in `raw/records.jsonl`.");
      lines.push("");
    }
    if (record.type === "tool_call") {
      lines.push(`Tool call \`${record.toolCallId ?? "unknown"}\``);
      lines.push("");
      lines.push(fence(record.content));
    } else if (record.type === "tool_result") {
      lines.push(`Tool result \`${record.toolCallId ?? "unknown"}\``);
      lines.push("");
      lines.push(fence(record.content));
    } else {
      lines.push(record.content || "_(empty)_");
    }
    lines.push("");
  });
  if (view.tool_pairs.length > 0) {
    lines.push("## Tool events");
    lines.push("");
    lines.push("| Call | Status |");
    lines.push("| --- | --- |");
    for (const pair of view.tool_pairs) lines.push(`| ${pair.callId} | ${pair.status} |`);
    lines.push("");
  }
  if (view.attachments.length > 0) {
    lines.push("## Attachments");
    lines.push("");
    lines.push("| Name | Bytes | SHA-256 | Status |");
    lines.push("| --- | --- | --- | --- |");
    for (const attachment of view.attachments) {
      lines.push(
        `| ${attachment.name} | ${attachment.bytes} | ${attachment.sha256 ?? "unavailable"} | ${attachment.status} |`,
      );
    }
    lines.push("");
  }
  lines.push("## Evidence ledger");
  lines.push("");
  lines.push("| Seq | Role | Provenance | Record hash | Timestamp |");
  lines.push("| --- | --- | --- | --- | --- |");
  for (const record of view.records) {
    lines.push(
      `| ${record.seq} | ${record.role} | ${record.provenance} | ${record.hash.slice(0, 16)} | ${record.timestamp ?? "unknown"} |`,
    );
  }
  lines.push("");
  lines.push("---");
  lines.push("");
  lines.push(
    `Generated by export-conversation 3.0.0. Coverage is relative to the source boundary; unknown records are preserved, not omitted.`,
  );
  lines.push("");
  return lines.join("\n");
}
